#!/usr/bin/env python3
"""Generate a Metro static image registry from an inspected local RepDB archive."""
import argparse
import json
import re
from pathlib import Path


def generate(root):
    data = json.loads((root / 'free.en.json').read_text(encoding='utf-8'))
    if data.get('schema_version') != 3 or data.get('source') != 'repdb-free':
        raise ValueError('Unsupported RepDB archive')
    records = data.get('exercises')
    if not isinstance(records, list) or not records:
        raise ValueError('No exercises in archive')
    entries = []
    seen = set()
    for row in records:
        key = row.get('id')
        if not isinstance(key, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', key) or key in seen:
            raise ValueError('Invalid or duplicate exercise ID')
        seen.add(key)
        poses = row.get('images', {}).get('flat')
        if poses not in (['main'], ['start', 'peak']):
            raise ValueError(f'Unexpected poses for {key}')
        pose = poses[0]
        relative = f'images/flat/{key}-{pose}.webp'
        image = root / relative
        if not image.is_file() or image.is_symlink():
            raise ValueError(f'Missing or unsafe image for {key}')
        header = image.read_bytes()[:12]
        if len(header) != 12 or header[:4] != b'RIFF' or header[8:12] != b'WEBP':
            raise ValueError(f'Invalid image for {key}')
        entries.append(f'  {json.dumps(key)}: require({json.dumps("./" + relative)}),')
    output = '// Generated by scripts/catalog/generate_bundle.py; do not edit.\nmodule.exports = {\n' + '\n'.join(entries) + '\n};\n'
    (root / 'image-registry.js').write_text(output, encoding='utf-8')
    return len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path)
    args = parser.parse_args()
    print(f'Generated registry for {generate(args.root)} exercises')


if __name__ == '__main__':
    main()
